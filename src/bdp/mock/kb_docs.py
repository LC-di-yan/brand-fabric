        for spu in spus_by_tenant.get(spec.tenant_id, []):
            seq += 1
            word = rng.choice(spec.product_words)
            rng.choice([w for w in spec.product_words if w != word] or spec.product_words)  # 措辞扰动参与下方组合
            spec_desc = "、".join(_sku_specs(spu["category_l1"])[:3])
