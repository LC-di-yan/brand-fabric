                f"可选规格：{spec_desc}。不同规格仅在尺寸与配色上存在差异，"
                f"面料配比（{fabric} {blend}）与工艺一致。",
                f"材质与工艺：主要成分为{fabric}混纺（配比 {blend}），"
                f"具备良好的回弹与速干表现，日常洗涤后不易变形。",
                f"洗涤建议：{temp} 度以下机洗，选择{wash}，避免漂白与高温烘干；"
